package dbconn

// The built-in functions of MySQL 8.4 and MariaDB 11.8 that an agent's
// statement may name before a parenthesis, and which of the two servers
// has each. The names come from each server's help tables (the function
// categories, without those for loadable functions, components and
// plugins) and from MariaDB's information_schema.SQL_FUNCTIONS, minus the
// loadable functions a stock server registers. A script outside the
// repository gathers them; the classes are set by hand, by reading every
// name. TestAgentFunctionsCoverServer checks the list against a server.

// funcClass says what calling a function can do.
type funcClass uint8

const (
	classPure    funcClass = iota + 1 // computes from its arguments alone
	classSession                      // reads the session's own state
	classTime                         // reads the clock
	classWait                         // waits or burns time
	classLock                         // takes, frees or reads a user lock
	classFile                         // reads or writes a file on the server
	classServer                       // reads or changes the server's or replication's state, or is internal
	classAccount                      // returns an account or a host
)

// allowed reports whether an agent may call functions of the class.
func (c funcClass) allowed() bool {
	return c == classPure || c == classSession || c == classTime
}

// The servers a function is built into.
const (
	onMySQL uint8 = 1 << iota
	onMariaDB
)

type agentFunc struct {
	class   funcClass
	flavors uint8
}

